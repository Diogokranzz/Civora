export const PRIORITY_MATRIX: Record<ImpactLevel, Record<UrgencyLevel, PriorityLevel>> = {
  HIGH: {
    HIGH: 'CRITICAL',
    MEDIUM: 'HIGH',
    LOW: 'MEDIUM',
  },
  MEDIUM: {
    HIGH: 'HIGH',
    MEDIUM: 'MEDIUM',
    LOW: 'LOW',
  },
  LOW: {
    HIGH: 'MEDIUM',
    MEDIUM: 'LOW',
    LOW: 'LOW',
  },
};

export function calculatePriorityFromMatrix(
  impact: ImpactLevel,
  urgency: UrgencyLevel,
): PriorityLevel {
  return PRIORITY_MATRIX[impact][urgency];
}

